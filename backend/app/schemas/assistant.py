from datetime import date
from typing import Literal

from pydantic import Field, field_validator

from app.schemas.imports import CamelModel

MAX_MESSAGES = 20
MAX_MESSAGE_CHARS = 2000


class ChatMessage(CamelModel):
    role: Literal["user", "assistant"]
    content: str = Field(min_length=1, max_length=MAX_MESSAGE_CHARS)


class ChatRequest(CamelModel):
    messages: list[ChatMessage] = Field(min_length=1, max_length=MAX_MESSAGES)

    @field_validator("messages")
    @classmethod
    def last_message_is_from_user(cls, messages: list[ChatMessage]) -> list[ChatMessage]:
        if messages[-1].role != "user":
            raise ValueError("The last message must be from the user.")
        if not messages[-1].content.strip():
            raise ValueError("The question is empty.")
        return messages


class ChatResponse(CamelModel):
    reply: str
    # "ai" = generated by the model from the data summary;
    # "system" = fixed message (e.g. no data imported), no AI call made.
    answered_by: Literal["ai", "system"]
    model: str | None
    data_as_of: date | None
    customer_count: int


class AssistantStatus(CamelModel):
    provider: Literal["anthropic", "openai"]
    configured: bool
    model: str | None
    data_as_of: date | None
    customer_count: int
